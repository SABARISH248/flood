def get_all_districts() -> List[Dict[str, Any]]:
    """Return summary list (id, name, centroid) for all districts."""
    return [{"id": d["id"], "name": d["name"], "centroid": d["centroid"], "area_km2": d["area_km2"]} for d in TN_DISTRICTS]


def get_district_by_id(district_id: int) -> Dict[str, Any]:
    """Return full district record or raise KeyError."""
    for d in TN_DISTRICTS:
        if d["id"] == district_id:
            return d
    raise KeyError(f"District ID {district_id} not found")


def get_district_by_name(name: str) -> Dict[str, Any]:
    """Case-insensitive district lookup by name."""
    name_lower = name.lower().strip()
    for d in TN_DISTRICTS:
        if d["name"].lower() == name_lower or d["name"].lower().startswith(name_lower):
            return d
    raise KeyError(f"District '{name}' not found in Tamil Nadu registry")
